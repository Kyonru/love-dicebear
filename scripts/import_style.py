#!/usr/bin/env python3
"""Compile pinned definitions to Lua and refresh the bundled-style registry."""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PIN = (ROOT / 'vendor/dicebear-styles.commit').read_text().strip()


def lua(value, key=None):
    if isinstance(value, str):
        # JSON escapes used by these assets are also valid in Lua 5.1.
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return '{' + ','.join(lua(v) for v in value) + '}'
    if isinstance(value, dict):
        if key == 'attributes':
            # Lua maps have no insertion order; SVG attributes do.
            return lua([[k, v] for k, v in value.items()])
        return '{' + ','.join('[' + lua(k) + ']=' + lua(v, k)
                              for k, v in value.items()) + '}'
    raise ValueError(f'Unsupported value: {value!r}')


sources = sorted((ROOT / 'vendor').glob('*.json'))
selected = set(sys.argv[1:])
assert not selected - {p.stem for p in sources}, 'Unknown style name'
rows = []
for source in sources:
    data = source.read_bytes()
    definition = json.loads(data)
    meta = definition.get('meta', {})
    creator = meta.get('creator', {}).get('name', 'Unknown')
    license = meta.get('license', {})
    rows.append(f'| `{source.stem}` | {creator} | [{license.get("name", "Unknown")}]'
                f'({license.get("url", "")}) | [source](https://github.com/dicebear/styles/blob/{PIN}/src/{source.name}) |')
    if selected and source.stem not in selected:
        continue
    target = ROOT / 'love_dicebear/styles' / (source.stem + '.lua')
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('-- Generated by scripts/import_style.py; do not edit.\n'
                      f'-- {source.stem} by {creator}. See THIRD_PARTY.md and STYLES.md.\n'
                      '-- Source SHA256: ' + hashlib.sha256(data).hexdigest() + '\n'
                      'return ' + lua(definition) + '\n')
(ROOT / 'love_dicebear/styles/registry.lua').write_text(
    '-- Generated by scripts/import_style.py.\nreturn ' + lua([p.stem for p in sources]) + '\n')
(ROOT / 'STYLES.md').write_text('# Bundled styles\n\n'
    'Generated from the pinned upstream definitions. Artwork licenses are independent of the code license.\n\n'
    '| Style | Creator | License | Pinned definition |\n| --- | --- | --- | --- |\n'
    + '\n'.join(rows) + '\n')
