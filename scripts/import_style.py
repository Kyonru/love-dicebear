#!/usr/bin/env python3
"""Compile the pinned Bottts definition to Lua; no JSON parser needed at runtime."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'vendor/bottts.json'


def lua(value, key=None):
    if isinstance(value, str):
        # JSON escapes used by these assets are also valid in Lua 5.1.
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return '{' + ','.join(lua(v) for v in value) + '}'
    if isinstance(value, dict):
        if key == 'attributes':
            # Lua maps have no insertion order; SVG attributes do.
            return lua([[k, v] for k, v in value.items()])
        return '{' + ','.join('[' + lua(k) + ']=' + lua(v, k)
                              for k, v in value.items()) + '}'
    raise ValueError(f'Unsupported value: {value!r}')


data = SOURCE.read_bytes()
definition = json.loads(data)
target = ROOT / 'love_dicebear/styles/bottts.lua'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text('-- Generated by scripts/import_style.py; do not edit.\n'
                  '-- Bottts by Pablo Stanley. See THIRD_PARTY.md.\n'
                  '-- Source SHA256: ' + hashlib.sha256(data).hexdigest() + '\n'
                  'return ' + lua(definition) + '\n')
