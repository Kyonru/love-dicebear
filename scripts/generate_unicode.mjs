// Pin Unicode data for initials rather than depending on the host Lua locale.
// Regenerate intentionally with Node 24 (Unicode 17.0); no runtime Node dependency.
import { mkdirSync, writeFileSync } from 'node:fs';
if (process.versions.unicode !== '17.0') throw new Error('Use Node with Unicode 17.0 to reproduce this table');
const letters = [], marks = [], upper = [];
function range(ranges, cp) {
  if (ranges.at(-1) === cp - 1) ranges[ranges.length - 1] = cp;
  else ranges.push(cp,cp);
}
for (let cp = 0; cp <= 0x10ffff; cp++) {
  const char = String.fromCodePoint(cp);
  if (/\p{L}/u.test(char)) range(letters,cp);
  if (/\p{M}/u.test(char)) range(marks,cp);
  const uppercase = char.toUpperCase();
  if (uppercase !== char) upper.push(`[${cp}]=${JSON.stringify(uppercase)}`);
}
mkdirSync('love_dicebear/data',{recursive:true});
writeFileSync('love_dicebear/data/unicode.lua',
  '-- Generated by scripts/generate_unicode.mjs; Unicode 17.0.\nreturn {\n'
  + `letters={${letters.join(',')}},\nmarks={${marks.join(',')}},\nupper={${upper.join(',')}}\n}\n`);
